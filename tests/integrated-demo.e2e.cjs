  assert.equal(o.total,first.price+99);
  let st=await panel.evaluate(id=>({available:window.IQCommerceDemo.available(window.IQCommerceDemo.get(),id),stock:window.IQCommerceDemo.get().products.find(p=>p.id===id).stock}),first.id);
